// "2 days ago" / "منذ يومين", for the Last activity column.
export function ago(b: BrokerDict, date: Date, now = new Date()): string {
  const ms = now.getTime() - date.getTime();
  if (ms < 60 * 60 * 1000) return b.justNow;
  const days = Math.floor(ms / (24 * 60 * 60 * 1000));
  if (days < 30) return b.agoDays(days);
  return b.agoMonths(Math.floor(days / 30));
}
