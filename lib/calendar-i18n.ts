// Arabic counting: 1, 2, 3 to 10, 11 and up.
function pla(n: number, one: string, two: string, few: string, many: string) {
  return n === 1 ? one : n === 2 ? two : (n >= 3 && n <= 10 ? few : many).replace("{n}", String(n));
}

