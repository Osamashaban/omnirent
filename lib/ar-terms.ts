const AR = new Map(TERMS.map(([en, ar]) => [en, ar]));
const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
// Longest first, so "holiday home" wins over "home". Whole words only.
const PATTERN = new RegExp(
  "(?<![A-Za-z0-9_@.\\-])(" +
    [...AR.keys()].sort((a, b) => b.length - a.length).map(escape).join("|") +
    ")(?![A-Za-z0-9_@\\-])",
  "gi",
);

export function arabicTerms(text: string): string {
  return text.replace(PATTERN, (m) => AR.get(m.toLowerCase()) ?? m);
}
