export const DICTS: Record<Lang, Dict> = { ar, en };

// Built-in modules are named in the viewer's language; anything else falls
// back to the single name stored in the database.
export function moduleName(t: Dict, module: { key: string; name: string }): string {
  const value = (t as Record<string, unknown>)[`module${module.key}`];
  return typeof value === "string" ? value : module.name;
}

export function moduleDescription(t: Dict, module: { key: string; description: string | null }): string {
  const value = (t as Record<string, unknown>)[`module${module.key}Desc`];
  return typeof value === "string" ? value : (module.description ?? "");
}
